@mcp.tool()
def calculate_lift_coefficient(
    lift_force_n: float,
    density_kg_m3: float,
    velocity_m_s: float,
    reference_area_m2: float,
) -> dict:
    """Calculate the dimensionless lift coefficient from lift force and flow conditions.

    Determines the lift coefficient (CL) that characterizes the lift-generating
    capability of a body.

    Required inputs:
        lift_force_n: Lift force in newtons (N). Must be finite; may be
                      negative or zero.
        density_kg_m3: Air density in kilograms per cubic metre (kg/m^3).
                       Must be strictly positive.
        velocity_m_s: Flow velocity in metres per second (m/s).
                      Must be strictly positive (zero velocity would make the
                      denominator zero).
        reference_area_m2: Reference area in square metres (m^2).
                           Must be strictly positive.

    Returns:
        A dictionary with the dimensionless lift coefficient, the unit
        "dimensionless", and the governing equation.

    Governing equation:
        CL = L / (0.5 * density * velocity**2 * area)
    """
    result = lift_coefficient(
        lift_force_n, density_kg_m3, velocity_m_s, reference_area_m2
    )
    return {
        "result": result,
        "unit": "dimensionless",
        "equation": "CL = L / (0.5 * density * velocity**2 * area)",
    }


@mcp.tool()
def calculate_reynolds_number(
    density_kg_m3: float,
    velocity_m_s: float,
    characteristic_length_m: float,
    dynamic_viscosity_pa_s: float,
) -> dict:
    """Calculate the dimensionless Reynolds number from flow and fluid properties.

    Determines the Reynolds number (Re), which characterizes the flow regime
    (laminar or turbulent) around a body.

    Required inputs:
        density_kg_m3: Air density in kilograms per cubic metre (kg/m^3).
                       Must be strictly positive.
        velocity_m_s: Flow velocity in metres per second (m/s).
                      Must be non-negative.
        characteristic_length_m: Characteristic length in metres (m).
                                 Must be strictly positive.
        dynamic_viscosity_pa_s: Dynamic viscosity in pascal-seconds (Pa*s).
                                Must be strictly positive.

    Returns:
        A dictionary with the dimensionless Reynolds number, the unit
        "dimensionless", and the governing equation.

    Governing equation:
        Re = density * velocity * characteristic_length / dynamic_viscosity
    """
    result = reynolds_number(
        density_kg_m3,
        velocity_m_s,
        characteristic_length_m,
        dynamic_viscosity_pa_s,
    )
    return {
        "result": result,
        "unit": "dimensionless",
        "equation": (
            "Re = density * velocity * characteristic_length / dynamic_viscosity"
        ),
    }


@mcp.tool()
def calculate_isa_troposphere(
    geopotential_altitude_m: float,
) -> dict:
    """Calculate International Standard Atmosphere properties in the troposphere.

    Computes temperature, pressure, density, and speed of sound using the
    1976 U.S. Standard Atmosphere tropospheric model (NASA/TM-2005-213659,
    Appendix A).

    Required inputs:
        geopotential_altitude_m: Geopotential altitude in metres (m).
                                 Must be between 0 and 11000 inclusive.
                                 This represents geopotential altitude, not
                                 geometric altitude.

    The model assumes dry air, hydrostatic equilibrium, ideal gas behaviour,
    constant gravitational acceleration, constant specific gas constant, and
    constant ratio of specific heats.

    Returns:
        A structured dictionary containing:

        * ``result``: Atmospheric properties including geopotential altitude,
          temperature, pressure, density, and speed of sound.
        * ``units``: SI units for every returned property.
        * ``model``: The atmospheric model identifier string.
        * ``valid_altitude_range_m``: The valid altitude range [0, 11000] m.

    Governing equations:
        Temperature:     T = T0 - L * H
        Pressure:        P = P0 * (T / T0) ** (g0 / (R * L))
        Density:         rho = P / (R * T)
        Speed of sound:  a = sqrt(gamma * R * T)
    """
    result = isa_troposphere(geopotential_altitude_m)
    return {
        "result": result,
        "units": {
            "geopotential_altitude_m": "m",
            "temperature_k": "K",
            "pressure_pa": "Pa",
            "density_kg_m3": "kg/m^3",
            "speed_of_sound_m_s": "m/s",
        },
        "model": "1976 U.S. Standard Atmosphere - Troposphere",
        "valid_altitude_range_m": [0.0, 11000.0],
    }


if __name__ == "__main__":
    mcp.run()
