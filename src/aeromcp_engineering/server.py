"""MCP server interface for AeroMCP.

This module implements the Model Context Protocol server that exposes
AeroMCP's validated aerospace engineering calculations as tools to AI clients.

The engineering calculation layer is completely independent of this MCP
interface. This server merely wraps the existing calculation functions
as MCP tools.
"""

