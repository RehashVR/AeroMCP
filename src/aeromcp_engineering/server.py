@mcp.tool()
def calculate_dynamic_pressure(
    density_kg_m3: float,
    velocity_m_s: float,
) -> dict:
    """Calculate dynamic pressure from air density and flow velocity.

    Determines the dynamic pressure (q) of a fluid flow, which represents
    the kinetic energy per unit volume of the fluid.

    Required inputs:
        density_kg_m3: Air density in kilograms per cubic metre (kg/m^3).
                       Must be strictly positive.
        velocity_m_s: Flow velocity in metres per second (m/s).
                      Must be non-negative.

    Returns:
        A dictionary with the dynamic pressure in pascals (Pa), the SI unit,
        and the governing equation.

    Governing equation:
        q = 0.5 * density * velocity**2
    """
    result = dynamic_pressure(density_kg_m3, velocity_m_s)
    return {
        "result": result,
        "unit": "Pa",
        "equation": "q = 0.5 * density * velocity**2",
    }


@mcp.tool()
def calculate_lift_force(
    density_kg_m3: float,
    velocity_m_s: float,
    reference_area_m2: float,
    lift_coefficient: float,
) -> dict:
    """Calculate lift force from air density, velocity, area, and lift coefficient.

    Determines the aerodynamic lift force generated by a body moving through
    a fluid.

    Required inputs:
        density_kg_m3: Air density in kilograms per cubic metre (kg/m^3).
                       Must be strictly positive.
        velocity_m_s: Flow velocity in metres per second (m/s).
                      Must be non-negative.
        reference_area_m2: Reference area in square metres (m^2).
                           Must be strictly positive.
        lift_coefficient: Dimensionless lift coefficient. May be negative,
                          zero, or positive, but must be finite.

    Returns:
        A dictionary with the lift force in newtons (N), the SI unit,
        and the governing equation.

    Governing equation:
        L = q * S * CL = 0.5 * density * velocity**2 * area * CL
    """
    result = lift_force(
        density_kg_m3, velocity_m_s, reference_area_m2, lift_coefficient
    )
    return {
        "result": result,
        "unit": "N",
        "equation": "L = 0.5 * density * velocity**2 * area * CL",
    }


